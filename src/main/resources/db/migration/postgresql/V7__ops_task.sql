-- P4 15주차. 청소 태스크 자동화와 칸반.
--
-- V1 에 ops_task 가 있지만 둘이 어긋난다. V1 을 고치지 않고 새 버전을 더한다.

-- ---------------------------------------------------------------------
-- 1. 담당자는 이름 문자열이다
-- ---------------------------------------------------------------------
--
-- V1 의 assignee_id 는 user_account 를 가리킨다. 담당자에게 계정을 주려면 역할별
-- 인가가 필요하고 그건 ADR 0004 가 3~5단계로 미뤄 둔 것이다. 지금 열면 인증 설계
-- 전체를 다시 본다(작업지시 12 의 5절 3번).
--
-- assignee_id 는 지우지 않는다. 담당자가 직접 로그인해 완료 처리를 하게 되는 시점에
-- 그 자리가 그대로 쓰인다. 그때까지는 비어 있다.
ALTER TABLE ops_task ADD COLUMN assignee_name VARCHAR(100);

-- 칸반이 담당자로 거른다. 숙소 안에서 이름으로 좁히는 경로다.
CREATE INDEX idx_task_assignee ON ops_task (property_id, assignee_name)
    WHERE assignee_name IS NOT NULL;

-- ---------------------------------------------------------------------
-- 2. 한 예약에 같은 종류의 태스크는 하나다
-- ---------------------------------------------------------------------
--
-- **유일 인덱스가 이 절의 존재 이유다.** Outbox 는 최소 1회 전달이라 같은 체크아웃
-- 이벤트가 두 번 올 수 있다. 애플리케이션에서 "이미 만들었나" 를 확인하고 넣으면
-- 그 사이에 두 번째가 끼어든다. 데이터베이스가 막게 한다. V6 의 uq_dispatch_once 와
-- 같은 자리다.
--
-- **이것은 같은 이벤트가 두 번 오는 것을 막는 장치다.** 옛 이벤트가 처음 오는 것은
-- 막지 못한다 — 소비자를 새로 붙일 때 Outbox 백로그가 비어 있어야 하는 이유이고,
-- 확인-05 7절이 그 관측이다.
--
-- reservation_id 가 없는 태스크(사람이 손으로 만든 것)는 이 제약을 받지 않는다.
CREATE UNIQUE INDEX uq_task_reservation ON ops_task (reservation_id, task_type)
    WHERE reservation_id IS NOT NULL;
